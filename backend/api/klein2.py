"""Klein 2.0 — statue-reference posing (v1.200.0).

A separate, self-contained lane next to the classic Klein pipeline (which stays
untouched).  The concept, in one line: instead of driving pose with depth /
normal control maps, hand Klein two ordinary reference IMAGES —

  image 1  the character rendered from EXACTLY the camera angle we need,
           snapshotted in the browser from a fully TEXTURED, rotatable 3D
           "statue" of the character (existing Hunyuan mesh + TRELLIS.2
           multi-view texturing from the real turnaround views), and
  image 2  a plain picture of the target pose (a neutral gray mannequin image
           generated by Klein t2i from a STORED, editable prompt — the
           "Pose Library 2.0" — or an uploaded pose photo),

then prompt "the character from image 1 in the pose from image 2".

Endpoints (prefix /api/klein2):
  characters                    list characters + mesh/statue readiness
  statue/generate               texture the stored mesh on a TRELLIS.2 worker
  statue/status/{name}          poll the statue run
  statue/{name}/glb             serve textured statue (fallback: untextured)
  poses …                       Pose Library 2.0 CRUD + regenerate + seeding
  generate / gen/{gid} …        the 2–3-ref Klein generation batch
  health                        preflight: klein workers + TRELLIS.2 node scan

Storage:
  <project_dir>/mesh3d/<char_id>/statue.glb + statue.json     textured statue
  <project_dir>/_libraries/klein2/poses/                      pose library 2.0
  <project_dir>/_libraries/klein2/_gen/_gen_<gid>/            generation batches

Worker notes: generation needs a 'klein'-capable worker (same as the Workshop);
statue texturing needs a worker with the ComfyUI-Trellis2 custom nodes.  The
texture graph is built DEFENSIVELY from the worker's /object_info (the pack's
node names may drift between versions — same approach as the UniRig graph in
char_mesh.py), and `workflows/KLEIN2_TRELLIS2_TEXTURE.json`, if present, is
used as an exact template instead (placeholders %MESH%, %VIEW_FRONT%,
%VIEW_LEFT%, %VIEW_BACK%, %VIEW_RIGHT%, %PREFIX%).  GET /health shows the
wiring plan BEFORE any run is spent.
"""
