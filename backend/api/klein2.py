def _klein_t2i_graph(prompt: str, w: int, h: int, seed: int) -> dict:
    path = _WORKFLOWS_DIR / "KLEIN_EDIT_ULTRA_WORKFLOW_Text2Image.json"
    if not path.exists():
        raise FileNotFoundError("workflow KLEIN_EDIT_ULTRA_WORKFLOW_Text2Image.json not found")
    return prepare_klein_workflow(str(path), prompt, w, h, seed)


def _run_prompt_blocking(client, workflow: dict, timeout_s: float = 420.0):
    res = client.queue_prompt(workflow)
    if isinstance(res, dict) and (res.get("node_errors") or res.get("error")):
        raise RuntimeError("worker rejected the graph: "
                           + json.dumps({k: res.get(k) for k in ("error", "node_errors")})[:600])
    pid = res.get("prompt_id") if isinstance(res, dict) else None
    if not pid:
        raise RuntimeError("worker did not return a prompt_id")
    t0 = time.time()
    while time.time() - t0 < timeout_s:
        time.sleep(1.2)
        try:
            hist = client.get_full_history(pid)
        except Exception:
            continue
        entry = hist.get(pid) if isinstance(hist, dict) else None
        if entry and entry.get("outputs"):
            return entry["outputs"]
    raise TimeoutError("worker timed out")


def _images_from_outputs(outputs: dict) -> list:
    out: list = []
    for node_out in outputs.values():
        if not isinstance(node_out, dict):
            continue
        for f in (node_out.get("images") or []):
            if isinstance(f, dict) and f.get("filename") and f.get("type") != "temp":
                out.append({"filename": f["filename"], "subfolder": f.get("subfolder", ""),
                            "type": f.get("type", "output")})
    return out


def _gen_pose_image_sync(disp, prompt: str, seed: int) -> bytes:
    _w, client = _klein_worker(disp)
    if not client:
        raise RuntimeError("no klein-capable worker online")
    wf = _klein_t2i_graph(prompt, 832, 1216, seed)
    outputs = _run_prompt_blocking(client, wf)
    imgs = _images_from_outputs(outputs)
    if not imgs:
        raise RuntimeError("worker produced no image")
    pick = imgs[-1]
    return client.download_output(pick["filename"], pick.get("subfolder", ""),
                                  pick.get("type", "output"))


