@router.post("/poses/import")
async def poses_import(file: UploadFile = File(...), raw_all: bool = Form(False),
                       category: Optional[str] = Form(None),
                       view: Optional[str] = Form(None)):
    """Batch-import pose DEFINITIONS (name + prompt [+ category] [+ raw]) from a
    JSON array/{poses:[...]} or a CSV with name,prompt[,category][,raw] headers.
    Records are created WITHOUT images (has_image=false) — run
    /poses/generate-missing afterwards to render them all across the workers.
    Prompts get the gray-mannequin style wrapper unless raw (per-row or raw_all).
    Duplicate names (case-insensitive) are skipped."""
    _ensure_dirs()
    data = await file.read()
    if not data:
        raise HTTPException(400, "empty file")
    text = data.decode("utf-8-sig", errors="replace")
    rows: List[dict] = []
    parsed = None
    try:
        obj = json.loads(text)
        parsed = (obj.get("poses") or obj.get("items")) if isinstance(obj, dict) else obj
    except Exception:
        parsed = None
    if isinstance(parsed, list):
        rows = [{str(k).strip().lower(): v for k, v in r.items()}
                for r in parsed if isinstance(r, dict)]
    else:
        import csv as _csv
        import io as _io
        try:
            dialect = _csv.Sniffer().sniff(text[:2048], delimiters=",;\t")
        except Exception:
            dialect = _csv.excel
        for r in _csv.DictReader(_io.StringIO(text), dialect=dialect):
            rows.append({(k or "").strip().lower(): (v or "").strip()
                         for k, v in r.items() if k is not None})
    if not rows:
        raise HTTPException(400, "no rows found — expected JSON [{name,prompt,category?,raw?}] "
                            "or CSV with name,prompt[,category][,raw] headers")
    tgt = (category or "").strip()
    if not tgt:
        raise HTTPException(400, "open (or create) a pose set first — imports always "
                            "land in the set you have open")
    _ensure_set(tgt)
    items = _read_poses()
    # Name-dupes are scoped PER SET (same pose name may exist in two sets).
    existing = {str(it.get("name", "")).strip().lower()
                for it in items if (it.get("set") or "Custom") == tgt}
    added: List[dict] = []
    skipped = 0
    for r in rows:
        name = str(r.get("name") or r.get("pose") or "").strip()
        prompt = str(r.get("prompt") or r.get("description") or "").strip()
        if not name or not prompt or name.lower() in existing:
            skipped += 1
            continue
        # v1.203: the row's category/tags describe the POSE — they become TAGS,
        # never the set name (the set is what the user opened).
        tags = _norm_tags(f"{r.get('category') or ''},{r.get('tags') or ''}")
        raw = bool(raw_all) or str(r.get("raw", "")).strip().lower() in ("1", "true", "yes", "y")
        # DOMINANT ANGLE: explicit row field wins, then the form default, then a
        # guess from the pose NAME (never from the prompt text — too noisy).
        rec_view = _norm_view(r.get("view") or r.get("angle") or r.get("dominant_angle")
                              or r.get("facing") or r.get("direction"))
        if not rec_view:
            rec_view = _norm_view(view) or _view_from_name(name)
        rec = {"id": uuid4().hex[:12], "name": name, "set": tgt, "category": tgt,
               "tags": tags[:8], "view": rec_view,
               "prompt": prompt if raw else _POSE_STYLE.format(pose=prompt),
               "source": "imported", "seed": None,
               "created_at": _now_iso(), "updated_at": _now_iso()}
        items.append(rec)
        existing.add(name.lower())
        added.append(_pose_public(rec))
    _write_poses(items)
    return {"imported": len(added), "skipped": skipped, "category": tgt, "poses": added}


# ── Pose PACK import: zip of images and/or OpenPose JSON keypoints ───────────
# Community pose packs come as folders of control images (openpose skeleton
# renders, depth maps, DWpose renders — any image works as image 2) or as raw
# OpenPose keypoint JSONs, which we render to the standard skeleton image
# ourselves (pure PIL drawing — no worker needed).

# canonical OpenPose rainbow colors + limb pairs (COCO-18 and BODY_25 orders)
_OP_COLORS = [(255, 0, 0), (255, 85, 0), (255, 170, 0), (255, 255, 0), (170, 255, 0),
              (85, 255, 0), (0, 255, 0), (0, 255, 85), (0, 255, 170), (0, 255, 255),
              (0, 170, 255), (0, 85, 255), (0, 0, 255), (85, 0, 255), (170, 0, 255),
              (255, 0, 255), (255, 0, 170), (255, 0, 85)]
_OP_LIMBS_18 = [(1, 2), (1, 5), (2, 3), (3, 4), (5, 6), (6, 7), (1, 8), (8, 9), (9, 10),
                (1, 11), (11, 12), (12, 13), (1, 0), (0, 14), (14, 15), (0, 16), (16, 17)]
_OP_LIMBS_25 = [(1, 2), (1, 5), (2, 3), (3, 4), (5, 6), (6, 7), (1, 8), (8, 9), (9, 10),
                (10, 11), (8, 12), (12, 13), (13, 14), (1, 0), (0, 15), (15, 16),
                (0, 17), (17, 18)]


def _save_pose_png(raw: bytes, dest: Path) -> None:
    """Normalize arbitrary image bytes to PNG on disk (RGBA-safe)."""
    from io import BytesIO
    from PIL import Image
    img = Image.open(BytesIO(raw))
    if img.mode not in ("RGB", "RGBA"):
        img = img.convert("RGB")
    dest.parent.mkdir(parents=True, exist_ok=True)
    img.save(dest, "PNG")


def _render_openpose_json(obj: dict) -> Optional[bytes]:
    """Render OpenPose keypoint JSON to the standard skeleton PNG.  Supports the
    official output format ({people:[{pose_keypoints_2d:[x,y,c,...]}]}) with
    COCO-18 or BODY_25 counts, optional canvas_width/canvas_height (editor
    exports), and a bare {keypoints:[...]} single-person variant."""
    from io import BytesIO
    from PIL import Image, ImageDraw
    if not isinstance(obj, dict):
        return None
    people = obj.get("people")
    if not people and isinstance(obj.get("keypoints"), list):
        people = [{"pose_keypoints_2d": obj["keypoints"]}]
    if not isinstance(people, list) or not people:
        return None
    persons: List[List[tuple]] = []
    for p in people:
        kp = p.get("pose_keypoints_2d") or p.get("keypoints") or []
        if not isinstance(kp, list) or len(kp) < 18 * 3:
            continue
        pts = [(float(kp[i]), float(kp[i + 1]), float(kp[i + 2]))
               for i in range(0, len(kp) - 2, 3)]
        persons.append(pts)
    if not persons:
        return None
    w = int(obj.get("canvas_width") or obj.get("width") or 0)
    h = int(obj.get("canvas_height") or obj.get("height") or 0)
    xs = [x for pts in persons for (x, y, c) in pts if c > 0.05]
    ys = [y for pts in persons for (x, y, c) in pts if c > 0.05]
    if not xs:
        return None
    if w <= 0 or h <= 0:
        # normalized coords (0..1) or pixel coords without a canvas
        if max(xs) <= 1.5 and max(ys) <= 1.5:
            w, h = 832, 1216
            persons = [[(x * w, y * h, c) for (x, y, c) in pts] for pts in persons]
        else:
            w, h = int(max(xs) * 1.15) + 20, int(max(ys) * 1.1) + 20
    img = Image.new("RGB", (max(64, w), max(64, h)), (0, 0, 0))
    draw = ImageDraw.Draw(img)
    lw = max(3, int(min(w, h) * 0.012))
    for pts in persons:
        limbs = _OP_LIMBS_25 if len(pts) >= 25 else _OP_LIMBS_18
        for li, (a, b) in enumerate(limbs):
            if a >= len(pts) or b >= len(pts):
                continue
            xa, ya, ca = pts[a]
            xb, yb, cb = pts[b]
            if ca <= 0.05 or cb <= 0.05:
                continue
            draw.line([(xa, ya), (xb, yb)], fill=_OP_COLORS[li % len(_OP_COLORS)], width=lw)
        for ji, (x, y, c) in enumerate(pts[:25]):
            if c > 0.05:
                r = lw
                draw.ellipse([x - r, y - r, x + r, y + r],
                             fill=_OP_COLORS[ji % len(_OP_COLORS)])
    buf = BytesIO()
    img.save(buf, "PNG")
    return buf.getvalue()


@router.post("/poses/import-pack")
async def poses_import_pack(file: UploadFile = File(...), category: Optional[str] = Form(None),
                            view: Optional[str] = Form(None)):
    """Batch-import a pose PACK: a .zip of control images (openpose skeleton /
    depth / DWpose renders — any image) and/or OpenPose keypoint .json files
    (rendered to skeleton PNGs server-side), or a single such .json.  Every
    entry becomes an image pose (source 'upload', no prompt) named from its
    filename — the generate prompt's pose-diagram note applies automatically."""
    _ensure_dirs()
    data = await file.read()
    if not data:
        raise HTTPException(400, "empty file")
    fname = (file.filename or "").lower()
    cat = (category or "").strip()
    entries: List[tuple] = []            # (name, kind 'image'|'json', bytes)
    if fname.endswith(".zip"):
        import zipfile as _zf
        from io import BytesIO
        try:
            zf = _zf.ZipFile(BytesIO(data))
        except Exception as e:
            raise HTTPException(400, f"unreadable zip: {e}")
        for info in zf.infolist()[:400]:
            n = info.filename
            base = n.rsplit("/", 1)[-1]
            if info.is_dir() or "__MACOSX" in n or base.startswith("."):
                continue
            ext = base.rsplit(".", 1)[-1].lower() if "." in base else ""
            if ext in ("png", "jpg", "jpeg", "webp", "bmp"):
                entries.append((base.rsplit(".", 1)[0], "image", zf.read(info)))
            elif ext == "json":
                entries.append((base.rsplit(".", 1)[0], "json", zf.read(info)))
    elif fname.endswith(".json"):
        entries.append(((file.filename or "pose").rsplit(".", 1)[0], "json", data))
    else:
        raise HTTPException(400, "expected a .zip pack or an openpose .json")
    if not entries:
        raise HTTPException(400, "no usable images or .json files found in the pack")
    if len(entries) > 200:
        entries = entries[:200]
    if not cat:
        raise HTTPException(400, "open (or create) a pose set first — packs always "
                            "land in the set you have open")
    _ensure_set(cat)
    items = _read_poses()
    existing = {str(it.get("name", "")).strip().lower()
                for it in items if (it.get("set") or "Custom") == cat}
    added, skipped, errors = [], 0, []
    for name, kind, raw in entries:
        nm = name.replace("_", " ").replace("-", " ").strip()[:60] or "pose"
        if nm.lower() in existing:
            skipped += 1
            continue
        try:
            if kind == "image":
                pid = uuid4().hex[:12]
                _save_pose_png(raw, _K2_POSES / f"{pid}.png")
            else:
                obj = json.loads(raw.decode("utf-8-sig", errors="replace"))
                png = _render_openpose_json(obj)
                if not png:
                    errors.append(f"{nm}: not a recognizable openpose keypoint json")
                    continue
                pid = uuid4().hex[:12]
                (_K2_POSES / f"{pid}.png").write_bytes(png)
        except Exception as e:  # noqa: BLE001
            errors.append(f"{nm}: {type(e).__name__}: {e}")
            continue
        rec = {"id": pid, "name": nm, "set": cat, "category": cat,
               "tags": [], "prompt": "",
               "view": _view_from_name(name) or _norm_view(view),
               "source": "upload", "seed": None,
               "created_at": _now_iso(), "updated_at": _now_iso()}
        items.append(rec)
        existing.add(nm.lower())
        added.append(_pose_public(rec))
    _write_poses(items)
    return {"imported": len(added), "skipped": skipped,
            "errors": errors[:10], "poses": added}


_BATCH_RUN: Dict[str, Any] = {}


def _klein_worker_pool(disp) -> List[tuple]:
    """All healthy klein-capable (non-runpod) workers as (short_url, client)."""
    out: List[tuple] = []
    try:
        for w in (getattr(disp, "workers", {}) or {}).values():
            if getattr(w, "healthy", False) and not getattr(w, "is_runpod", False) \
                    and "klein" in (getattr(w, "capabilities", set()) or set()):
                cl = disp.clients.get(w.url)
                if cl:
                    out.append((str(w.url).replace("http://", "").replace("https://", "").rstrip("/"), cl))
    except Exception:  # noqa: BLE001
        pass
    if not out:
        _w, cl = _klein_worker(disp)
        if cl:
            out.append((getattr(_w, "url", "worker"), cl))
    return out


