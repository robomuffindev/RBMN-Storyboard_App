@router.post("/statue/generate")
async def statue_generate(body: StatueIn, request: Request,
                          session: AsyncSession = Depends(get_session)):
    _ensure_dirs()
    name = body.character_name.strip()
    if (_STATUE_RUNS.get(name) or {}).get("status") == "running":
        raise HTTPException(409, "A statue run is already in progress for this character.")
    char = await _char_by_name(session, name)
    cid = str(char.id)
    mode = (body.mode or "generate").lower()
    if mode not in ("generate", "texture"):
        raise HTTPException(400, "mode must be 'generate' or 'texture'")
    mesh_fp = _mesh3d_dir(cid) / "character.glb"
    mesh_bytes_opt: Optional[bytes] = None
    if mode == "texture":
        if not mesh_fp.exists():
            raise HTTPException(409, "No 3D mesh yet — generate the 3D body first "
                                "(Create tab → 🧊 Generate 3D body), or use mode "
                                "'generate' (TRELLIS builds its own geometry).")
        mesh_bytes_opt = mesh_fp.read_bytes()
    views = await _collect_views(session, char)
    disp = _dispatcher(request)
    urls = [body.host] if body.host else _worker_urls(disp)
    if not urls:
        raise HTTPException(409, "No workers online.")
    seed = int(body.seed) if body.seed else random.randint(1, 2_000_000_000)
    mesh_bytes = mesh_bytes_opt

    # quality preset -> texture-node overrides (explicit fields win)
    overrides: Dict[str, Any] = {}
    if (body.quality or "").lower() == "high":
        # community best-quality recipe (TRELLIS.2 #92 + wrapper docs): 4096 bake,
        # 1536 conditioning, more steps, guidance ~2.5 (also counters the known
        # baked-in-shading darkness; the node default 3.0 runs slightly hot)
        overrides = {"texture_size": 4096, "resolution": 1536, "texture_steps": 24,
                     "texture_guidance_strength": 2.5,
                     # generate mode only (texture mode has no such input): higher
                     # voxel tier = better face/finger geometry; tiled decoder +
                     # FP8 should hold 16GB, OOM fails clean if not
                     "pipeline_type": "1536_cascade"}
    for fld in ("texture_size", "texture_steps", "resolution"):
        v = getattr(body, fld)
        if v is not None:
            overrides[fld] = int(v)
    if body.texture_guidance_strength is not None:
        overrides["texture_guidance_strength"] = float(body.texture_guidance_strength)

    _STATUE_RUNS[name] = {"status": "running", "phase": "scan", "error": None,
                          "started_at": _now_iso(), "host": None,
                          "mode": mode, "quality": body.quality or "standard"}

    def _run_sync():
        st = _STATUE_RUNS[name]
        try:
            # 1) find a worker with the Trellis2 pack (or validate the template)
            chosen = None
            oi = None
            errs = []
            for u in urls:
                try:
                    o = _fetch_object_info(u)
                    if _trellis_pack(o) or (mode == "texture"
                                            and (_WORKFLOWS_DIR / "KLEIN2_TRELLIS2_TEXTURE.json").exists()):
                        chosen, oi = u, o
                        break
                except Exception as e:  # noqa: BLE001
                    errs.append(f"{u}: {e}")
            if not chosen:
                raise RuntimeError("No worker with TRELLIS.2 nodes found. " +
                                   ("; ".join(errs) if errs else "See /api/klein2/health."))
            st["host"] = chosen
            st["phase"] = "upload"
            disp2 = disp
            client = disp2.clients.get(chosen) if disp2 else None
            if client is None:
                raise RuntimeError(f"no client for worker {chosen}")

            token = uuid4().hex[:8]
            with tempfile.TemporaryDirectory() as td:
                tdp = Path(td)
                mesh_name = f"k2_statue_{token}.glb"
                if mode == "texture" and mesh_bytes is not None:
                    (tdp / mesh_name).write_bytes(mesh_bytes)
                    client.upload_image(str(tdp / mesh_name), mesh_name)
                up_views: Dict[str, str] = {}
                for vl in ("front", "left", "back", "right"):
                    if vl not in views:
                        continue
                    fn = f"k2_statue_{token}_{vl}.png"
                    (tdp / fn).write_bytes(views[vl])
                    client.upload_image(str(tdp / fn), fn)
                    up_views[vl] = fn

            prefix = f"rbmn_klein2/statue_{token}"
            if mode == "generate":
                graph, plan = build_trellis_generate_graph(
                    oi, views=up_views, filename_prefix=prefix, seed=seed,
                    overrides=overrides)
            else:
                graph = _template_graph(mesh_name, up_views, prefix)
                plan = {"template": True} if graph else None
                if graph is None:
                    graph, plan = build_trellis_graph(
                        oi, mesh_filename=mesh_name, views=up_views,
                        filename_prefix=prefix, seed=seed, overrides=overrides)
            # keep the exact graph for diagnosis (measure, don't infer)
            diag = _mesh3d_dir(cid)
            diag.mkdir(parents=True, exist_ok=True)
            (diag / "statue_graph.json").write_text(json.dumps(
                {"host": chosen, "plan": plan, "graph": graph}, indent=2), "utf-8")

            st["phase"] = "texture"
            res = client.queue_prompt(graph)
            if isinstance(res, dict) and (res.get("node_errors") or res.get("error")):
                raise RuntimeError("worker REJECTED the graph at validation: "
                                   + json.dumps({k: res.get(k) for k in ("error", "node_errors")})[:900]
                                   + " -- see statue_graph.json")
            pid = res.get("prompt_id") if isinstance(res, dict) else None
            if not pid:
                raise RuntimeError("worker did not return a prompt_id")
            deadline = time.time() + 3600
            entry = None
            done = False
            while time.time() < deadline:
                time.sleep(4)
                try:
                    hist = client.get_full_history(pid)
                except Exception:
                    continue
                entry = hist.get(pid) if isinstance(hist, dict) else None
                if entry and (entry.get("outputs") or (entry.get("status") or {}).get("completed")):
                    done = True
                    break
            if not done:
                raise TimeoutError("texture run timed out (60 min)")

            from backend.services.character_studio.vnccs_native.char_mesh import harvest_output_files
            glbs = harvest_output_files(entry or {}, (".glb",))
            st["phase"] = "download"
            data = None
            if glbs:
                g = glbs[0]
                data = client.download_output(g.get("filename", ""), g.get("subfolder", "") or "",
                                              g.get("type", "output") or "output")
            else:
                # Trellis2ExportMesh is an OUTPUT node but reports no files in
                # history ui -- its filename is deterministic:
                # <prefix>_<counter:05>_.glb, and our token-unique prefix means
                # the counter starts at 1.
                sub, _, base = prefix.replace("\\", "/").rpartition("/")
                for c in (1, 2, 3):
                    try:
                        data = client.download_output(f"{base}_{c:05}_.glb", sub, "output")
                        if data:
                            break
                    except Exception:
                        data = None
            if not data:
                raise RuntimeError("worker produced no GLB — check statue_graph.json "
                                   "and the worker console")
            (diag / "statue.glb").write_bytes(data)
            meta = {"created_at": _now_iso(), "host": chosen, "seed": seed,
                    "mode": mode, "quality": (overrides or {}).get("texture_size") or "standard",
                    "views": sorted(up_views), "bytes": len(data),
                    "plan": {k: v for k, v in (plan or {}).items() if k != "texture_inputs"}}
            (diag / "statue.json").write_text(json.dumps(meta, indent=2), "utf-8")
            st.update({"status": "done", "phase": "done", "meta": meta})
            logger.info("klein2 statue[%s]: done (%d bytes, host %s)", name, len(data), chosen)
        except Exception as e:  # noqa: BLE001
            logger.exception("klein2 statue[%s] failed", name)
            st.update({"status": "error", "error": f"{type(e).__name__}: {e}"})

    task = asyncio.create_task(asyncio.to_thread(_run_sync))
    _BG_TASKS.add(task)
    task.add_done_callback(_BG_TASKS.discard)
    return {"started": True, "character": name, "seed": seed}


