def _best_base_version(v: dict) -> Optional[dict]:
    """Prefer the active base if it's a multi-view set, else a mesh-ready set,
    else any multi-view set, else the active/latest (mirrors mesh3d)."""
    versions = [b for b in (v.get("base_versions") or []) if isinstance(b, dict)]
    active = v.get("active_base")
    act = next((b for b in versions if b.get("id") == active), None)

    def mode(b):
        return str((b.get("gen_meta") or {}).get("base_mode") or "").lower()

    def is_set(b):
        return len(b.get("views") or []) > 1 or mode(b) in ("mesh", "set")
    if act is not None and is_set(act):
        return act
    mesh = [b for b in versions if mode(b) == "mesh"]
    sets = [b for b in versions if len(b.get("views") or []) > 1]
    return (mesh[-1] if mesh else (sets[-1] if sets else
            (act or (versions[-1] if versions else None))))


async def _collect_views(session: AsyncSession, char: StudioCharacter) -> Dict[str, bytes]:
    v = (char.manifest or {}).get("vnccs") or {}
    bv = _best_base_version(v)
    if not bv or not bv.get("asset_id"):
        raise HTTPException(status_code=409, detail="No base version — generate a base first.")
    views: Dict[str, bytes] = {}
    front = await _asset_bytes(session, bv.get("asset_id"))
    if not front:
        raise HTTPException(status_code=409, detail="Base image is not readable.")
    views["front"] = front
    for vw in (bv.get("views") or []):
        vl = str(vw.get("view") or "").lower()
        if vl in ("left", "back", "right") and vw.get("asset_id"):
            data = await _asset_bytes(session, vw.get("asset_id"))
            if data:
                views[vl] = data
    return views


