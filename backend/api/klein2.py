# ── TRELLIS.2 graph (defensive, mirrors char_mesh's UniRig approach) ─────────
def _norm(s: str) -> str:
    return str(s).lower().replace(" ", "").replace("_", "").replace("-", "").replace(".", "")


def _trellis_pack(oi: dict) -> Dict[str, dict]:
    """All node classes registered by the Trellis2 custom-node pack, identified
    by python_module (robust against display-name drift)."""
    out: Dict[str, dict] = {}
    for k, v in (oi or {}).items():
        mod = _norm((v or {}).get("python_module") or "")
        if "trellis2" in mod or "trellis" in _norm(k):
            out[k] = v or {}
    return out


def _input_spec(oi: dict, class_type: str) -> Dict[str, tuple]:
    """{input_name: (kind, default_or_options_or_linktype)} — same shape as
    char_mesh._input_spec, duplicated here so klein2 stays self-contained."""
    out: Dict[str, tuple] = {}
    node = (oi or {}).get(class_type) or {}
    for section in ("required", "optional"):
        for name, spec in ((node.get("input") or {}).get(section) or {}).items():
            if not isinstance(spec, (list, tuple)) or not spec:
                continue
            first = spec[0]
            c = spec[1] if len(spec) > 1 and isinstance(spec[1], dict) else {}
            if isinstance(first, list):
                # v1.200.8: honor the combo's DECLARED default by moving it to
                # the front (fill-defaults picks [0]).  Taking the raw first
                # option set device="cpu" on Trellis2LoadModel (options are
                # [cpu, cuda], default cuda) -> CPU/CUDA tensor mismatch.
                opts = list(first)
                dv = c.get("default")
                if dv in opts and opts and opts[0] != dv:
                    opts = [dv] + [o for o in opts if o != dv]
                out[name] = ("combo", opts)
            elif isinstance(first, str) and first in ("INT", "FLOAT", "STRING", "BOOLEAN"):
                out[name] = (first.lower(), c.get("default"))
            else:
                out[name] = ("link", str(first))
    return out


def _fill_defaults(spec: Dict[str, tuple]) -> Dict[str, Any]:
    inputs: Dict[str, Any] = {}
    for name, (kind, dv) in spec.items():
        if kind == "combo" and isinstance(dv, list) and dv:
            inputs[name] = dv[0]
        elif kind in ("int", "float", "string", "boolean") and dv is not None:
            inputs[name] = dv
    return inputs


def _pick_class(pack: Dict[str, dict], *needle_sets: Tuple[str, ...]) -> Optional[str]:
    for needles in needle_sets:
        for k in pack:
            nk = _norm(k)
            if all(n in nk for n in needles):
                return k
    return None


def _make_model_loader_inputs(oi: dict, loader_cls: str) -> Dict[str, Any]:
    """Trellis2LoadModel inputs tuned for 16GB workers: FP8 checkpoint,
    device=cuda, backend=sdpa, sparse_backend=xformers, low_vram=True."""
    ml_spec = _input_spec(oi, loader_cls)
    ml_in = _fill_defaults(ml_spec)
    for mk, (mkind, mdv) in ml_spec.items():
        lk = mk.lower()
        if mkind == "combo" and isinstance(mdv, list) and mdv:
            if "model" in lk or "ckpt" in lk:
                fp8 = next((o for o in mdv if "fp8" in str(o).lower()), None)
                if fp8:
                    ml_in[mk] = fp8
            if lk == "backend":
                sdpa = next((o for o in mdv if "sdpa" in str(o).lower()), None)
                if sdpa:
                    ml_in[mk] = sdpa
            if lk == "sparse_backend":
                xf = next((o for o in mdv if "xformers" in str(o).lower()), None)
                if xf:
                    ml_in[mk] = xf
            if lk == "device":
                cu = next((o for o in mdv if str(o).lower() == "cuda"), None)
                if cu:
                    ml_in[mk] = cu
        if mkind == "boolean" and lk.replace("_", "") == "lowvram":
            ml_in[mk] = True
    return ml_in


def _type_matched_saver(oi: dict, pack: Dict[str, dict], out_types: List[str]) -> Optional[dict]:
    """A pack save/export class whose link input accepts one of ``out_types``;
    prefers glb-capable nodes.  Returns {class, link_input, from_output,
    format_input} or None."""
    cands = []
    for cls in pack:
        n = _norm(cls)
        if "export" not in n and "save" not in n:
            continue
        c_spec = _input_spec(oi, cls)
        link = next((k for k, (kind, _t) in c_spec.items() if kind == "link"), None)
        if not link:
            continue
        ltype = str(c_spec[link][1]).upper()
        if ltype not in out_types:
            continue
        fmt_key = next((k for k, (kind, ov) in c_spec.items()
                        if kind == "combo" and isinstance(ov, list)
                        and any(str(o).lower() == "glb" for o in ov)), None)
        glbish = 1 if (fmt_key or "glb" in n) else 0
        cands.append((-glbish, len(cls), cls, link, out_types.index(ltype), fmt_key))
    if not cands:
        return None
    cands.sort()
    _g, _len, cls, link, out_idx, fmt_key = cands[0]
    return {"class": cls, "link_input": link, "from_output": out_idx, "format_input": fmt_key}


def plan_trellis_graph(oi: dict) -> dict:
    """Dry-run: which classes WOULD be used and how.  Returned by /health so the
    wiring is inspectable before a single run is spent.  Raises ValueError with
    a readable diagnostic when the worker can't do it."""
    pack = _trellis_pack(oi)
    if not pack:
        raise ValueError("No ComfyUI-Trellis2 nodes on this worker — install "
                         "visualbruno/ComfyUI-Trellis2 (+ its wheels + the DINOv3 "
                         "model) and restart ComfyUI.")
    tex = _pick_class(pack, ("texturing", "multi"), ("texturing",), ("texture",))
    if not tex:
        raise ValueError("Trellis2 pack found but no Mesh-Texturing class. Classes "
                         "present: " + ", ".join(sorted(pack)))
    spec = _input_spec(oi, tex)
    mesh_link = next((k for k, (kind, t) in spec.items()
                      if kind == "link" and "MESH" in str(t).upper()), None)
    mesh_path = None
    if not mesh_link:
        mesh_path = next((k for k in spec
                          if any(n in k.lower() for n in ("mesh", "glb", "model_path", "file"))
                          and spec[k][0] in ("combo", "string")), None)
    image_links = [k for k, (kind, t) in spec.items()
                   if kind == "link" and "IMAGE" in str(t).upper()]
    loader = None
    if mesh_link:
        loader = _pick_class(pack, ("load", "mesh"), ("load", "glb"), ("import", "mesh"),
                             ("load", "model"), ("load", "3d"))
        if not loader:
            raise ValueError(f"{tex} takes a mesh LINK but the pack has no mesh loader "
                             "class. Classes present: " + ", ".join(sorted(pack)))
    if not mesh_link and not mesh_path:
        raise ValueError(f"{tex}: no mesh input found (inputs: {sorted(spec)})")
    if not image_links:
        raise ValueError(f"{tex}: no IMAGE input found (inputs: {sorted(spec)})")
    # Saver: TYPE-MATCHED against the texture node's actual output types.
    # Measured 2026-08-01: texturing returns (TRIMESH, IMAGE, IMAGE) and the
    # pack has BOTH a TRIMESH exporter (Trellis2ExportMesh, file_format combo
    # with 'glb') and a MESHWITHVOXEL one (Trellis2OvoxelExportToGLB) -- name
    # matching alone picked the wrong node (return_type_mismatch at validation).
    tex_outputs = [str(t).upper() for t in ((oi.get(tex) or {}).get("output") or [])]
    save_pick = _type_matched_saver(oi, pack, tex_outputs)
    if not save_pick:
        raise ValueError(
            f"No save/export node accepts {tex}'s output types {tex_outputs} -- "
            "classes present: " + ", ".join(sorted(pack)))
    return {
        "texture_class": tex,
        "texture_inputs": {k: list(v) for k, v in spec.items()},
        "texture_outputs": tex_outputs,
        "mesh_via": {"link": mesh_link, "loader": loader} if mesh_link else {"path_input": mesh_path},
        "image_inputs": image_links,
        "model_loader": _pick_class(pack, ("load", "model"), ("model", "loader")),
        "save": save_pick,
        "save_class": save_pick["class"],
        "pack_classes": sorted(pack),
    }


def _wire_views_with_preprocess(
    oi: dict, pack: Dict[str, dict], api: Dict[str, dict],
    order: List[str], views: Dict[str, str],
) -> Dict[str, list]:
    """LoadImage each view and, when the pack has a PreProcessImage class, run
    every view through it (remove_background=True, crop-to-object, max 1024 —
    matching the pack's own example workflows).  Feeding RAW plate renders
    straight into the generators conditions DINOv3 on the background and wrong
    framing → holes / wrong proportions (measured on Duke statue #3).
    Returns {view: node_ref} to wire into the generator/texturing node."""
    refs: Dict[str, list] = {}
    pre_cls = _pick_class(pack, ("preprocess", "image"))
    for vl in order:
        api[f"img_{vl}"] = {"class_type": "LoadImage", "inputs": {"image": views[vl]}}
        refs[vl] = [f"img_{vl}", 0]
        if not pre_cls:
            continue
        p_spec = _input_spec(oi, pre_cls)
        img_key = next((k for k, (kind, t) in p_spec.items()
                        if kind == "link" and "IMAGE" in str(t).upper()), None)
        if not img_key:
            continue
        p_in = _fill_defaults(p_spec)
        p_in[img_key] = [f"img_{vl}", 0]
        for k in p_spec:
            lk = k.lower()
            if "remove" in lk and "background" in lk:
                p_in[k] = True              # our views come on solid plates
            elif lk == "padding":
                p_in[k] = 10                # example-workflow value
            elif "max_size" in lk:
                p_in[k] = 2048     # don't discard upscaled source sets at the door
        api[f"pre_{vl}"] = {"class_type": pre_cls, "inputs": p_in}
        refs[vl] = [f"pre_{vl}", 0]
    return refs


def build_trellis_graph(
    oi: dict, *, mesh_filename: str, views: Dict[str, str],
    filename_prefix: str, seed: int, overrides: Optional[Dict[str, Any]] = None,
) -> Tuple[Dict[str, dict], dict]:
    """Texture graph from the wiring plan.  ``views`` maps front/left/back/right
    to uploaded worker filenames.  Named per-view IMAGE inputs (front_image,
    back_image, ... — Trellis2MeshTexturingMultiView style) are wired by NAME;
    a single IMAGE input gets an ImageBatch chain (Trellis2MeshTexturing style).

    16GB-VRAM guards (researched 2026-08-01, workers are 16GB cards):
    - model loader: prefer the FP8 checkpoint option, low_vram=True, backend=sdpa
      (the pack ships no flash-attn wheel);
    - texture node: texture_size clamped to <=2048 (the pack default 4096 needs
      ~16GB for the UV bake ALONE), conditioning resolution 1024."""
    plan = plan_trellis_graph(oi)
    api: Dict[str, dict] = {}
    tex = plan["texture_class"]
    spec = _input_spec(oi, tex)
    tex_in = _fill_defaults(spec)

    # seed, if the node has one
    for k in spec:
        if k.lower() in ("seed", "noise_seed"):
            tex_in[k] = int(seed)

    # mesh
    mesh_via = plan["mesh_via"]
    if mesh_via.get("link"):
        loader = mesh_via["loader"]
        l_spec = _input_spec(oi, loader)
        l_in = _fill_defaults(l_spec)
        pk = next((k for k in l_spec
                   if any(n in k.lower() for n in ("file", "path", "mesh", "glb"))
                   and l_spec[k][0] in ("combo", "string")), None)
        if pk is None:
            raise ValueError(f"{loader}: no path input (inputs: {sorted(l_spec)})")
        l_in[pk] = mesh_filename
        if "source_folder" in l_spec:
            l_in["source_folder"] = "input"
        api["mesh_load"] = {"class_type": loader, "inputs": l_in}
        tex_in[mesh_via["link"]] = ["mesh_load", 0]
    else:
        tex_in[mesh_via["path_input"]] = mesh_filename

    # view images — preprocessed (bg removal + crop), by NAME when the node has
    # per-view inputs, else batched
    order = [v for v in ("front", "left", "back", "right") if v in views]
    if not order:
        raise ValueError("no views to texture from")
    vrefs = _wire_views_with_preprocess(oi, _trellis_pack(oi), api, order, views)
    image_inputs = plan["image_inputs"]
    named: Dict[str, str] = {}
    for k in image_inputs:
        lk = k.lower()
        for vl in ("front", "back", "left", "right"):
            if vl in lk:
                named.setdefault(vl, k)
                break
    if named.get("front") or (named and "front" not in views):
        for vl in order:
            if named.get(vl):
                tex_in[named[vl]] = vrefs[vl]
    elif len(image_inputs) >= 1:
        ref = vrefs[order[0]]
        for vl in order[1:]:
            api[f"batch_{vl}"] = {"class_type": "ImageBatch",
                                  "inputs": {"image1": ref, "image2": vrefs[vl]}}
            ref = [f"batch_{vl}", 0]
        tex_in[image_inputs[0]] = ref

    # remaining link inputs (the Trellis2LoadModel-style model/pipe input)
    for k, (kind, t) in spec.items():
        if kind != "link" or isinstance(tex_in.get(k), list):
            continue
        tu = str(t).upper()
        if "IMAGE" in tu or "MESH" in tu:
            continue
        ld = plan.get("model_loader")
        if not ld:
            raise ValueError(f"{tex} needs a {t} link but the pack has no model-loader "
                             "class. Classes: " + ", ".join(sorted(_trellis_pack(oi))))
        if "model_load" not in api:
            api["model_load"] = {"class_type": ld,
                                 "inputs": _make_model_loader_inputs(oi, ld)}
        tex_in[k] = ["model_load", 0]

    # 16GB VRAM guards on the texture node itself
    for k, (kind, dv) in spec.items():
        lk = k.lower()
        if "texture_size" in lk or lk == "texture_resolution":
            if kind == "combo" and isinstance(dv, list):
                opts = [o for o in dv if str(o).isdigit() and int(o) <= 2048]
                if opts:
                    tex_in[k] = max(opts, key=lambda o: int(o))
            else:
                try:
                    cur = int(tex_in.get(k) or 0)
                except Exception:
                    cur = 0
                if cur == 0 or cur > 2048:
                    tex_in[k] = 2048
        elif lk == "resolution" and kind == "combo" and isinstance(dv, list):
            hit = next((o for o in dv if str(o) == "1024" or o == 1024), None)
            if hit is not None:
                tex_in[k] = hit
        elif kind == "boolean" and lk.replace("_", "") == "lowvram":
            tex_in[k] = True

    # explicit user overrides (quality dials) win over the 16GB guards
    for ok_, ov in (overrides or {}).items():
        if ov is None:
            continue
        name = next((n for n in spec if n.lower() == str(ok_).lower()), None)
        if name is None:
            continue
        kind, dv = spec[name]
        if kind == "combo" and isinstance(dv, list):
            hit = next((o for o in dv if o == ov or str(o) == str(ov)), None)
            if hit is not None:
                tex_in[name] = hit
        else:
            tex_in[name] = ov

    api["tex"] = {"class_type": tex, "inputs": tex_in}

    # save — node, link input, and tex OUTPUT INDEX were type-matched in the plan
    sv = plan["save"]
    s_spec = _input_spec(oi, sv["class"])
    s_in = _fill_defaults(s_spec)
    s_in[sv["link_input"]] = ["tex", int(sv.get("from_output") or 0)]
    if sv.get("format_input"):
        s_in[sv["format_input"]] = "glb"
    for k in s_spec:
        if "prefix" in k.lower() or k.lower() == "filename":
            s_in[k] = filename_prefix
    api["save"] = {"class_type": sv["class"], "inputs": s_in}
    return api, plan


def build_trellis_generate_graph(
    oi: dict, *, views: Dict[str, str], filename_prefix: str, seed: int,
    overrides: Optional[Dict[str, Any]] = None,
) -> Tuple[Dict[str, dict], dict]:
    """FULL statue generation: TRELLIS.2 image→3D multi-view — its OWN geometry
    (far better faces/hands than the Hunyuan rig mesh) AND texture, from the
    turnaround views.  The statue is only a snapshot reference, so its geometry
    is free to differ from the rigged mesh.

    Chain: Trellis2LoadModel → Trellis2MeshWithVoxelMultiViewGenerator
    (named front/back/left/right inputs, tiled decoder ON) → ovoxel export
    (bake, texture_size, decimation) → TRIMESH file exporter → GLB."""
    pack = _trellis_pack(oi)
    if not pack:
        raise ValueError("No ComfyUI-Trellis2 nodes on this worker.")
    gen = _pick_class(pack, ("meshwithvoxel", "multiview", "generator"),
                      ("multiview", "generator"))
    if not gen:
        raise ValueError("No multi-view generator class in the Trellis2 pack. "
                         "Classes: " + ", ".join(sorted(pack)))
    spec = _input_spec(oi, gen)
    g_in = _fill_defaults(spec)
    api: Dict[str, dict] = {}

    # pipeline/model link
    ld = _pick_class(pack, ("load", "model"), ("model", "loader"))
    if not ld:
        raise ValueError("No Trellis2 model-loader class found.")
    api["model_load"] = {"class_type": ld, "inputs": _make_model_loader_inputs(oi, ld)}
    for k, (kind, t) in spec.items():
        if kind == "link" and any(n in str(t).upper() for n in ("PIPE", "MODEL", "TRELLIS")):
            g_in[k] = ["model_load", 0]

    # views by name (front required), preprocessed (bg removal + crop — the
    # pack's example workflows ALWAYS do this before the generators)
    order = [v for v in ("front", "left", "back", "right") if v in views]
    if "front" not in views:
        raise ValueError("full statue generation needs at least the FRONT view")
    vrefs = _wire_views_with_preprocess(oi, pack, api, order, views)
    wired_any = False
    for k, (kind, t) in spec.items():
        if kind != "link" or "IMAGE" not in str(t).upper():
            continue
        lk = k.lower()
        for vl in ("front", "back", "left", "right"):
            if vl in lk and vl in views:
                g_in[k] = vrefs[vl]
                wired_any = True
                break
    if not wired_any:
        raise ValueError(f"{gen}: no per-view IMAGE inputs found (inputs: {sorted(spec)})")

    for k in spec:
        if k.lower() in ("seed", "noise_seed"):
            g_in[k] = int(seed)
    # generation-stage overrides (texture_steps / texture_guidance_strength / …)
    for ok_, ov in (overrides or {}).items():
        if ov is None:
            continue
        name = next((n for n in spec if n.lower() == str(ok_).lower()), None)
        if name is None:
            continue
        kind, dv = spec[name]
        if kind == "combo" and isinstance(dv, list):
            hit = next((o for o in dv if o == ov or str(o) == str(ov)), None)
            if hit is not None:
                g_in[name] = hit
        else:
            g_in[name] = ov
    api["gen"] = {"class_type": gen, "inputs": g_in}

    # ovoxel export: bake + decimate the generated MESHWITHVOXEL into a TRIMESH
    gen_outputs = [str(t).upper() for t in ((oi.get(gen) or {}).get("output") or [])]
    ovx = _type_matched_saver(oi, pack, gen_outputs)
    if not ovx:
        raise ValueError(f"No export node accepts {gen}'s outputs {gen_outputs}. "
                         "Classes: " + ", ".join(sorted(pack)))
    o_spec = _input_spec(oi, ovx["class"])
    o_in = _fill_defaults(o_spec)
    o_in[ovx["link_input"]] = ["gen", int(ovx.get("from_output") or 0)]
    tex_size = int((overrides or {}).get("texture_size") or 2048)
    for k, (kind, dv) in o_spec.items():
        lk = k.lower()
        if "texture_size" in lk:
            if kind == "combo" and isinstance(dv, list):
                hit = next((o for o in dv if str(o) == str(tex_size) or o == tex_size), None)
                if hit is not None:
                    o_in[k] = hit
            else:
                o_in[k] = tex_size
        elif "face" in lk and ("target" in lk or "num" in lk):
            o_in[k] = 500_000        # 2M default chokes the browser viewer
        elif "prefix" in lk or lk == "filename":
            o_in[k] = filename_prefix
    api["ovx"] = {"class_type": ovx["class"], "inputs": o_in}

    # file save: whatever exporter accepts the ovoxel node's output (TRIMESH)
    ovx_outputs = [str(t).upper() for t in ((oi.get(ovx["class"]) or {}).get("output") or [])]
    sv = _type_matched_saver(oi, {k: v for k, v in pack.items() if k != ovx["class"]},
                             ovx_outputs)
    if sv:
        s_spec = _input_spec(oi, sv["class"])
        s_in = _fill_defaults(s_spec)
        s_in[sv["link_input"]] = ["ovx", int(sv.get("from_output") or 0)]
        if sv.get("format_input"):
            s_in[sv["format_input"]] = "glb"
        for k in s_spec:
            if "prefix" in k.lower() or k.lower() == "filename":
                s_in[k] = filename_prefix
        api["save"] = {"class_type": sv["class"], "inputs": s_in}
    plan = {"mode": "generate", "generator_class": gen, "export_class": ovx["class"],
            "save_class": (sv or {}).get("class"), "views": order,
            "texture_size": tex_size}
    return api, plan


def _template_graph(mesh_filename: str, views: Dict[str, str], prefix: str) -> Optional[dict]:
    """Optional exact template: workflows/KLEIN2_TRELLIS2_TEXTURE.json (ComfyUI
    API format) with %MESH% / %VIEW_FRONT% / %VIEW_LEFT% / %VIEW_BACK% /
    %VIEW_RIGHT% / %PREFIX% placeholders.  Wins over the auto-builder when
    present, so a hand-exported known-good graph can be dropped in."""
    tp = _WORKFLOWS_DIR / "KLEIN2_TRELLIS2_TEXTURE.json"
    if not tp.exists():
        return None
    txt = tp.read_text("utf-8")
    subs = {"%MESH%": mesh_filename, "%PREFIX%": prefix,
            "%VIEW_FRONT%": views.get("front", ""), "%VIEW_LEFT%": views.get("left", ""),
            "%VIEW_BACK%": views.get("back", ""), "%VIEW_RIGHT%": views.get("right", "")}
    for k, v in subs.items():
        txt = txt.replace(k, v.replace("\\", "\\\\").replace('"', '\\"'))
    try:
        return json.loads(txt)
    except Exception as e:
        raise ValueError(f"KLEIN2_TRELLIS2_TEXTURE.json is not valid JSON after "
                         f"substitution: {e}")


