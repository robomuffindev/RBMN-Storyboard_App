@router.post("/poses/generate-missing")
async def poses_generate_missing(body: PoseBatchIn, request: Request):
    """Render every image-less prompt pose (e.g. fresh imports), fanned out
    across ALL klein workers with live per-pose worker/status."""
    _ensure_dirs()
    if (_BATCH_RUN or {}).get("status") == "running":
        raise HTTPException(409, "a pose batch generation is already running")
    items = _read_poses()
    want = set(body.ids or [])
    cat = (body.category or "").strip()
    targets = [it for it in items
               if (not want or it["id"] in want) and (it.get("prompt") or "").strip()
               and (not cat or (it.get("set") or "Custom") == cat)
               and not (_K2_POSES / f"{it['id']}.png").exists()]
    if not targets:
        return {"started": False, "note": "no image-less prompt poses to generate"}
    disp = _dispatcher(request)
    seed0 = int(body.seed) if body.seed else random.randint(1, 2_000_000_000)
    _BATCH_RUN.clear()
    _BATCH_RUN.update({"status": "running", "done": 0, "total": len(targets),
                       "tasks": {it["id"]: {"name": it.get("name", ""), "worker": None,
                                            "status": "queued", "error": None}
                                 for it in targets}})

    def _run():
        import queue as _q
        import threading
        workers = _klein_worker_pool(disp)
        if not workers:
            _BATCH_RUN.update({"status": "error", "errors": ["no klein-capable worker online"]})
            return
        qq: Any = _q.Queue()
        for i, it in enumerate(targets):
            qq.put((i, it))

        def _loop(short, client):
            while True:
                try:
                    i, it = qq.get_nowait()
                except _q.Empty:
                    return
                t = _BATCH_RUN["tasks"][it["id"]]
                t.update({"worker": short, "status": "running"})
                try:
                    wf = _klein_t2i_graph(it["prompt"], 832, 1216, seed0 + i)
                    outputs = _run_prompt_blocking(client, wf)
                    imgs = _images_from_outputs(outputs)
                    if not imgs:
                        raise RuntimeError("worker produced no image")
                    pick = imgs[-1]
                    data = client.download_output(pick["filename"], pick.get("subfolder", ""),
                                                  pick.get("type", "output"))
                    (_K2_POSES / f"{it['id']}.png").write_bytes(data)
                    t["status"] = "done"
                except Exception as e:  # noqa: BLE001
                    t.update({"status": "error", "error": f"{type(e).__name__}: {e}"})
                    logger.warning("pose batch %r on %s failed: %s", it.get("name"), short, e)
                _BATCH_RUN["done"] = sum(1 for x in _BATCH_RUN["tasks"].values()
                                         if x["status"] in ("done", "error"))

        ths = [threading.Thread(target=_loop, args=wc, daemon=True) for wc in workers]
        for th in ths:
            th.start()
        for th in ths:
            th.join()
        errs = [f"{v['name']}: {v['error']}" for v in _BATCH_RUN["tasks"].values()
                if v["status"] == "error"]
        _BATCH_RUN["errors"] = errs
        _BATCH_RUN["status"] = "done" if not errs else "done_with_errors"

    task = asyncio.create_task(asyncio.to_thread(_run))
    _BG_TASKS.add(task)
    task.add_done_callback(_BG_TASKS.discard)
    return {"started": True, "total": len(targets)}


