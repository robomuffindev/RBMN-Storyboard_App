class GenerateIn(BaseModel):
    character_name: str
    angle_png_b64: str               # the 📸 statue snapshot from the viewer
    pose_id: str
    prompt_extra: str = ""           # appended scene/outfit/etc. text
    include_front_ref: bool = True   # add the photoreal front base as image 3
    count: int = 2
    width: int = 832
    height: int = 1216
    seed: Optional[int] = None


@router.post("/generate")
async def generate(body: GenerateIn, request: Request,
                   session: AsyncSession = Depends(get_session)):
    _ensure_dirs()
    import base64
    name = body.character_name.strip()
    char = await _char_by_name(session, name)

    pose = next((it for it in _read_poses() if it.get("id") == body.pose_id), None)
    if pose is None:
        raise HTTPException(404, "pose not found")
    pose_fp = _K2_POSES / f"{body.pose_id}.png"
    if not pose_fp.exists():
        raise HTTPException(409, "pose image missing — regenerate it in the library")

    raw = body.angle_png_b64
    if "," in raw[:64]:                       # tolerate data: URLs
        raw = raw.split(",", 1)[1]
    try:
        angle_bytes = base64.b64decode(raw)
    except Exception:
        raise HTTPException(400, "angle_png_b64 is not valid base64")
    if not angle_bytes:
        raise HTTPException(400, "empty angle snapshot")

    front_bytes: Optional[bytes] = None
    if body.include_front_ref:
        try:
            v = (char.manifest or {}).get("vnccs") or {}
            bv = _best_base_version(v)
            if bv and bv.get("asset_id"):
                front_bytes = await _asset_bytes(session, bv.get("asset_id"))
        except Exception:
            front_bytes = None

    gid = uuid4().hex[:12]
    gd = _gen_dir(gid)
    gd.mkdir(parents=True, exist_ok=True)
    (gd / "ref_identity.png").write_bytes(angle_bytes)
    (gd / "ref_pose.png").write_bytes(pose_fp.read_bytes())
    ref_paths = [str(gd / "ref_identity.png"), str(gd / "ref_pose.png")]
    if front_bytes:
        (gd / "ref_front.png").write_bytes(front_bytes)
        ref_paths.append(str(gd / "ref_front.png"))

    prompt = _GEN_PROMPT_3REF if len(ref_paths) >= 3 else _GEN_PROMPT
    extra = body.prompt_extra.strip()
    if extra:
        prompt = f"{prompt} {extra}"

    disp = _dispatcher(request)
    _w, client = _klein_worker(disp)
    if not client:
        raise HTTPException(409, "No klein-capable worker online.")

    count = max(1, min(int(body.count or 1), 8))
    w = max(256, min(int(body.width or 832), 2048))
    h = max(256, min(int(body.height or 1216), 2048))
    base_seed = int(body.seed) if body.seed is not None else random.randint(1, 2_000_000_000)
    st = {"status": "running", "character": name, "pose": pose.get("name"),
          "pose_id": body.pose_id, "prompt": prompt, "total": count, "done": 0,
          "images": [], "error": None, "width": w, "height": h,
          "refs": [Path(p).name for p in ref_paths]}
    _write_gen(gid, st)

    def _run():
        errs: List[str] = []
        for i in range(count):
            try:
                _w2, cl = _klein_worker(disp)
                if not cl:
                    raise RuntimeError("no klein-capable worker online")
                ref_names: List[str] = []
                for rp in ref_paths:
                    up = f"k2_ref_{uuid4().hex[:8]}.png"
                    cl.upload_image(rp, up)
                    ref_names.append(up)
                n = max(1, min(len(ref_names), 5))
                fname = f"KLEIN_EDIT_ULTRA_WORKFLOW_{n}REF.json"
                path = _WORKFLOWS_DIR / fname
                if not path.exists():
                    raise FileNotFoundError(f"workflow {fname} not found")
                wf = prepare_klein_workflow(str(path), prompt, w, h, base_seed + i,
                                            ref_images=ref_names[:n])
                outputs = _run_prompt_blocking(cl, wf, 420)
                imgs = _images_from_outputs(outputs)
                if not imgs:
                    raise RuntimeError("worker produced no image")
                pick = imgs[-1]
                data = cl.download_output(pick["filename"], pick.get("subfolder", ""),
                                          pick.get("type", "output"))
                nm = f"{i}.png"
                (gd / nm).write_bytes(data)
                st["images"].append({"id": nm, "seed": base_seed + i})
            except Exception as e:  # noqa: BLE001
                errs.append(f"#{i + 1}: {type(e).__name__}: {e}")
                logger.warning("[klein2-gen %s] image %d failed: %s", gid, i, e)
            st["done"] = i + 1
            st["error"] = "; ".join(errs[-3:]) if errs else None
            _write_gen(gid, st)
        st["status"] = "done" if st["images"] else "error"
        if not st["images"] and not st["error"]:
            st["error"] = "all generations failed"
        _write_gen(gid, st)

    task = asyncio.create_task(asyncio.to_thread(_run))
    _BG_TASKS.add(task)
    task.add_done_callback(_BG_TASKS.discard)
    logger.info("klein2 generate[%s]: char=%s pose=%s refs=%d count=%d",
                gid, name, pose.get("name"), len(ref_paths), count)
    return {"gen_id": gid, "total": count, "prompt": prompt, "seed": base_seed,
            "refs": [Path(p).name for p in ref_paths]}


@router.get("/gen/{gid}")
async def gen_status(gid: str):
    st = _read_gen(gid)
    if st is None:
        raise HTTPException(404, "generation not found")
    imgs = [{"id": im["id"], "url": f"/api/klein2/gen/{gid}/image/{im['id']}",
             "seed": im.get("seed")} for im in st.get("images", [])]
    refs = [{"name": r, "url": f"/api/klein2/gen/{gid}/image/{r}"}
            for r in st.get("refs", [])]
    return {"gen_id": gid, "status": st.get("status"), "done": st.get("done", 0),
            "total": st.get("total", 0), "character": st.get("character"),
            "pose": st.get("pose"), "prompt": st.get("prompt", ""),
            "images": imgs, "refs": refs, "error": st.get("error")}


@router.get("/gen/{gid}/image/{name}")
async def gen_image(gid: str, name: str):
    if "/" in name or "\\" in name or ".." in name or "/" in gid or "\\" in gid or ".." in gid:
        raise HTTPException(400, "bad name")
    fp = _gen_dir(gid) / name
