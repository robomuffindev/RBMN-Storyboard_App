def _read_poses() -> List[dict]:
    if not _POSE_INDEX.exists():
        return []
    try:
        data = json.loads(_POSE_INDEX.read_text("utf-8"))
        items = data if isinstance(data, list) else []
    except Exception:
        return []
    # one-time migration: pre-v1.203 records used 'category' as the grouping —
    # that becomes the SET (so nothing disappears) AND a tag.
    changed = False
    for it in items:
        if "set" not in it:
            it["set"] = str(it.get("category") or "Custom")
            changed = True
        if "tags" not in it:
            it["tags"] = [str(it["category"])] if it.get("category") else []
            changed = True
        it["category"] = it["set"]          # legacy mirror (pinned Klein2Panel)
    if changed:
        try:
            _write_poses(items)
        except Exception:
            pass
    return items


