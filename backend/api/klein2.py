def _klein_worker(disp):
    """A healthy klein-capable worker (same policy as the Image Workshop)."""
    if not disp:
        return None, None
    w = None
    try:
        w = disp.select_worker({"klein"}, set(), exclude_runpod=True)
    except Exception:
        w = None
    if not w:
        try:
            w = disp.select_worker(set(), set(), exclude_runpod=True)
        except Exception:
            w = None
    if not w:
        return None, None
    return w, disp.clients.get(w.url)


def _fetch_object_info(url: str, timeout: float = 60.0) -> dict:
    """Raw /object_info from a worker (independent of client implementations)."""
    import requests
    r = requests.get(url.rstrip("/") + "/object_info", timeout=timeout)
    r.raise_for_status()
    data = r.json()
    if not isinstance(data, dict):
        raise RuntimeError("object_info: unexpected payload")
    return data


